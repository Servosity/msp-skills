#!/usr/bin/env python3
"""Hand-fix ledger gate.

Connectors in this repo are generated by cli-printing-press and then carry
connector-specific edits to GENERATED ("DO NOT EDIT") files: live-API quirks
(e.g. Python-style `id_` primary keys), synthesized identifiers, corrected
examples, and bug-fix back-ports. A `cli-printing-press` reprint regenerates
those files and can SILENTLY clobber those edits -- `go test` stays green
while the fix is gone (see docs/reprint-survival.md).

This gate is the enforcement layer. Each connector may carry a
`skills/<slug>/handfixes.json` ledger recording every such edit with a
grep-able marker. This check asserts every marker is still present (and any
banned anti-pattern is still absent) and FAILS CI if a reprint dropped one.

Ledger schema (skills/<slug>/handfixes.json):

    {
      "slug": "axcient",
      "doc": "docs/reprint-survival.md",
      "handfixes": [
        {
          "id": "id-key-primary-fallback",
          "summary": "one line",
          "why": "the live-API truth / rationale",
          "status": "active | upstreamed",   // optional, default "active"
          "spec_encode_followup": "...",      // optional
          "asserts": [
            {"file": "cli/internal/store/store.go", "contains": "\"id_\"", "min_count": 2},
            {"file": "cli/internal/mcp/tools.go",   "not_contains": "fmt.Sprintf(\"%v\", v), 1)"}
          ]
        }
      ]
    }

`status` is informational: "active" = a connector-only edit a reprint would
clobber; "upstreamed" = also fixed in the press (a reprint from a fixed press
regenerates it) but the back-port must still be present today. Both are
asserted present.

Usage:
    check_handfixes.py                 # every skill with a ledger
    check_handfixes.py --slug axcient  # one skill
    check_handfixes.py --all           # explicit all (same as no args)
    check_handfixes.py --changed --base <sha>   # PR-diff mode (CI)

Exit codes:
    0  every ledger passes (or none exist), or --changed found nothing unrecorded
    1  a real finding: a marker regressed, or a generated file was hand-edited
       without a ledger entry
    2  INTERNAL ERROR: the check could not run. Today the only such case is
       --changed being unable to compute a changed-file set (missing base ref,
       missing merge-base, no git). Exit 2 is deliberately distinct from 0: an
       uncomputable comparison base is NOT "nothing changed", and must never be
       reported as a pass - a reprint that dropped a registered security
       hand-fix would sail through. `--allow-missing-base` is the only opt-out
       and it prints SKIP, never PASS; CI never passes it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SKILLS = REPO / "skills"


def _load_ledger(path: Path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        return None, f"{path.relative_to(REPO)}: unreadable ledger ({e})"
    if not isinstance(data, dict) or not isinstance(data.get("handfixes"), list):
        return None, f"{path.relative_to(REPO)}: ledger must be an object with a 'handfixes' array"
    return data, None


def check_skill(slug: str) -> list[str]:
    """Return a list of failure messages (empty == pass) for one skill."""
    skill_dir = SKILLS / slug
    ledger_path = skill_dir / "handfixes.json"
    if not ledger_path.exists():
        return []  # no ledger -> nothing to enforce for this skill

    data, err = _load_ledger(ledger_path)
    if err or data is None:
        return [err or f"skills/{slug}/handfixes.json: unreadable ledger"]

    doc = data.get("doc", "docs/reprint-survival.md")
    failures: list[str] = []

    for hf in data["handfixes"]:
        hid = hf.get("id", "<unnamed>")
        asserts = hf.get("asserts", [])
        if not asserts:
            failures.append(f"[{slug}] handfix '{hid}' has no asserts; every ledger entry needs at least one grep-able marker")
            continue
        for a in asserts:
            rel = a.get("file")
            if not rel:
                failures.append(f"[{slug}] handfix '{hid}': assert missing 'file'")
                continue
            fpath = skill_dir / rel
            if not fpath.exists():
                failures.append(
                    f"[{slug}] handfix '{hid}': file '{rel}' is GONE. A reprint likely "
                    f"removed it. Restore the hand-fix or update skills/{slug}/handfixes.json. See {doc}."
                )
                continue
            content = fpath.read_text(encoding="utf-8", errors="replace")
            if "contains" in a:
                needle = a["contains"]
                min_count = int(a.get("min_count", 1))
                found = content.count(needle)
                if found < min_count:
                    failures.append(
                        f"[{slug}] handfix '{hid}' REGRESSED in {rel}: expected {min_count}x "
                        f"`{needle}`, found {found}. A reprint likely clobbered it. Restore the "
                        f"hand-fix (or, if intentionally changed, update skills/{slug}/handfixes.json). See {doc}."
                    )
            if "not_contains" in a:
                banned = a["not_contains"]
                if banned in content:
                    failures.append(
                        f"[{slug}] handfix '{hid}' REGRESSED in {rel}: banned anti-pattern "
                        f"`{banned}` is present again. A reprint likely reintroduced it. See {doc}."
                    )
            if "contains" not in a and "not_contains" not in a:
                failures.append(f"[{slug}] handfix '{hid}': assert for '{rel}' needs 'contains' or 'not_contains'")
    return failures


def brief(slug: str | None) -> int:
    """Print the ledger(s) as a pre-reprint briefing for the regenerating agent.

    Run this BEFORE reprinting or re-onboarding a connector so the agent knows
    which generated-file edits it must preserve. This is the proactive half of
    the contract; check (the default mode) is the reactive enforcement.
    """
    slugs = [slug] if slug else sorted(p.parent.name for p in SKILLS.glob("*/handfixes.json"))
    any_found = False
    for s in slugs:
        ledger_path = SKILLS / s / "handfixes.json"
        if not ledger_path.exists():
            continue
        data, err = _load_ledger(ledger_path)
        if err or data is None:
            print(f"[{s}] ledger unreadable: {err}", file=sys.stderr)
            continue
        any_found = True
        hfs = data["handfixes"]
        print(f"\n=== PRESERVE these {len(hfs)} hand-fix(es) when reprinting `{s}` ===")
        print("(connector edits to GENERATED files; a reprint will clobber them unless you re-apply)")
        for hf in hfs:
            status = hf.get("status", "active")
            print(f"\n- {hf.get('id', '<unnamed>')}  [{status}]: {hf.get('summary', '')}")
            if hf.get("why"):
                print(f"    why: {hf['why'].strip()}")
            if hf.get("spec_encode_followup"):
                print(f"    spec-encode: {hf['spec_encode_followup'].strip()}")
            for a in hf.get("asserts", []):
                if "contains" in a:
                    print(f"    keep:  {a['file']}  contains {a.get('min_count', 1)}x  {a['contains']!r}")
                if "not_contains" in a:
                    print(f"    avoid: {a['file']}  must NOT contain  {a['not_contains']!r}")
        print(f"\nAfter regenerating, run: python3 tools/maintainer/check_handfixes.py --slug {s}")
    if not any_found:
        target = f"`{slug}`" if slug else "any connector"
        print(f"No hand-fix ledger for {target}; nothing recorded to preserve.")
    return 0


# Comment substrings that flag a deliberate hand-edit to generated code.
_HANDFIX_MARKERS = ("Hand-wired:", "hand-wired", "hand-fix", "HANDFIX", "DO-NOT-REGEN", "pp-keep")


def discover() -> int:
    """List connectors whose generated code carries hand-fix markers but no
    ledger -- back-fill candidates. Marker-based, so it only finds *commented*
    hand-fixes; silent edits still need a reprint-diff to surface. Advisory."""
    rows: list[tuple[str, int]] = []
    for d in sorted(SKILLS.glob("*/cli")):
        slug = d.parent.name
        if (SKILLS / slug / "handfixes.json").exists():
            continue
        hits = 0
        for go in (d / "internal").rglob("*.go"):
            if go.name.endswith("_test.go"):
                continue
            try:
                text = go.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            if any(m in text for m in _HANDFIX_MARKERS):
                hits += 1
        if hits:
            rows.append((slug, hits))
    if not rows:
        print("No unrecorded hand-fix markers found. (Marker-based; silent edits not detected.)")
        return 0
    print("Connectors with hand-fix markers but NO handfixes.json ledger (back-fill candidates):\n")
    for slug, hits in rows:
        print(f"  - {slug}: {hits} file(s) with hand-fix markers")
    print("\nThese hand-fixes are NOT yet protected from a reprint. Add a")
    print("skills/<slug>/handfixes.json for each. See docs/reprint-survival.md.")
    print("\nNote: this only finds COMMENTED hand-fixes; silent edits still need a")
    print("reprint-diff to surface. Record fixes at fix-time so they never go silent.")
    return 0


_GENERATED_HEADER = "Generated by CLI Printing Press"
# A reprint changes most generated files at once; a hand-fix changes a few.
# Above this many changed generated files in one connector, treat the change as
# a reprint (the must-survive gate covers recorded fixes) rather than a
# hand-edit that needs its own ledger entry.
_REPRINT_THRESHOLD = 8


# Exit status for "this check could not run", kept distinct from both 0 (clean)
# and 1 (a real finding) so CI can never read a plumbing failure as a pass.
EXIT_INTERNAL_ERROR = 2


def _changed_files(base: str) -> tuple[list[str], str | None]:
    """Return (changed files, error). On error the file list is meaningless:
    callers MUST treat a non-None error as an internal error, never as an empty
    diff. Silently mapping "cannot compare" to "nothing changed" is exactly how
    a dropped hand-fix passes the gate."""
    import subprocess

    try:
        rp = subprocess.run(
            ["git", "-C", str(REPO), "rev-parse", "--verify", "--quiet", f"{base}^{{commit}}"],
            capture_output=True, text=True,
        )
    except FileNotFoundError:
        return [], "git is not available on PATH, so no comparison base could be resolved"
    if rp.returncode != 0:
        return [], (f"base ref '{base}' does not resolve to a commit in this checkout "
                    f"(fetch it, or deepen a shallow clone)")

    for diff_args in ([f"{base}...HEAD"], [base, "HEAD"], [base]):
        try:
            out = subprocess.run(
                ["git", "-C", str(REPO), "diff", "--name-only", *diff_args],
                capture_output=True, text=True, check=True,
            ).stdout
            return [l for l in out.splitlines() if l.strip()], None
        except (subprocess.CalledProcessError, FileNotFoundError):
            continue
    return [], (f"base ref '{base}' resolves, but no diff against it could be computed "
                f"(no merge-base with HEAD?)")


def changed(base: str, allow_missing_base: bool = False) -> int:
    """Flag generated-file edits in this change that are NOT recorded in a
    ledger -- so a NEW hand-fix gets recorded (and thus protected) the moment
    it is introduced. Fail-CLOSED on a detected unrecorded hand-edit AND on an
    uncomputable comparison base (exit 2, INTERNAL ERROR - the check did not
    run, which is not the same as "nothing changed"). Reprints (many generated
    files at once) are exempted from the must-record requirement; the
    must-survive gate covers recorded fixes there.

    `allow_missing_base` is the deliberate opt-out for a local checkout with no
    base ref. It prints SKIP (never PASS) so no reader can mistake it for a
    verified change, and CI never passes it."""
    files, err = _changed_files(base)
    if err:
        if allow_missing_base:
            print(f"SKIP: new-hand-fix diff check DID NOT RUN - {err}. "
                  f"Nothing was verified (--allow-missing-base was passed; CI never passes it).",
                  file=sys.stderr)
            print("SKIP (not a pass): new-hand-fix diff check did not run; no comparison base.")
            return 0
        print("INTERNAL ERROR: the new-hand-fix diff check could not run, so nothing was "
              "verified.", file=sys.stderr)
        print(f"  reason: {err}", file=sys.stderr)
        print("  This is NOT a pass: an uncomputable base is not an empty diff, and a reprint "
              "that dropped a registered hand-fix would go unnoticed.", file=sys.stderr)
        print("  Fix the base ref (in CI: checkout with fetch-depth: 0 and a valid "
              "pull_request.base.sha). For a deliberate local run without a base, pass "
              "--allow-missing-base, which prints SKIP and verifies nothing.", file=sys.stderr)
        return EXIT_INTERNAL_ERROR

    per_slug_generated: dict[str, list[str]] = {}
    ledger_touched: set[str] = set()
    for f in files:
        parts = f.split("/")
        if len(parts) < 2 or parts[0] != "skills":
            continue
        slug = parts[1]
        if f == f"skills/{slug}/handfixes.json":
            ledger_touched.add(slug)
            continue
        # generated Go under cli/internal or cli/cmd, excluding tests
        if not (f.startswith(f"skills/{slug}/cli/internal/") or f.startswith(f"skills/{slug}/cli/cmd/")):
            continue
        if not f.endswith(".go") or f.endswith("_test.go"):
            continue
        fpath = REPO / f
        if not fpath.exists():
            continue  # deletion; skip
        head = "".join(fpath.read_text(encoding="utf-8", errors="replace").splitlines(keepends=True)[:3])
        if _GENERATED_HEADER in head:
            per_slug_generated.setdefault(slug, []).append(f)

    failures: list[str] = []
    for slug, gen_files in sorted(per_slug_generated.items()):
        if slug in ledger_touched:
            continue  # the hand-fix was recorded in the same change
        if len(gen_files) > _REPRINT_THRESHOLD:
            print(f"info: {slug}: {len(gen_files)} generated files changed (treated as a reprint; "
                  f"the must-survive gate covers recorded fixes).")
            continue
        sample = ", ".join(gen_files[:4]) + (" ..." if len(gen_files) > 4 else "")
        failures.append(
            f"[{slug}] edited generated file(s) without recording a hand-fix: {sample}. "
            f"Edits to `DO NOT EDIT` files are clobbered on the next reprint unless recorded. "
            f"Add/extend skills/{slug}/handfixes.json in this change (or encode the behavior in "
            f"the spec). See docs/reprint-survival.md."
        )

    if failures:
        print("FAIL: generated-file hand-edits not recorded in a hand-fix ledger:\n")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("PASS: every generated-file hand-edit in this change is recorded (or part of a reprint).")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="Connector hand-fix ledger: enforce, brief, or discover.")
    ap.add_argument("--slug", help="one skill (default: all skills with a ledger)")
    ap.add_argument("--all", action="store_true", help="every skill (default behavior)")
    ap.add_argument("--brief", action="store_true",
                    help="print the ledger as a pre-reprint briefing (run BEFORE regenerating)")
    ap.add_argument("--discover", action="store_true",
                    help="list connectors with hand-fix markers but no ledger (back-fill candidates)")
    ap.add_argument("--changed", action="store_true",
                    help="flag generated-file edits in this change that aren't recorded in a ledger")
    ap.add_argument("--base", default="origin/main",
                    help="base ref for --changed (default: origin/main)")
    ap.add_argument("--allow-missing-base", action="store_true",
                    help="--changed only: if the base ref cannot be resolved, print SKIP and "
                         "exit 0 instead of the INTERNAL ERROR exit 2. Verifies NOTHING. For "
                         "local checkouts without a base ref; CI must never pass this.")
    args = ap.parse_args()

    if args.discover:
        return discover()
    if args.changed:
        return changed(args.base, allow_missing_base=args.allow_missing_base)
    if args.brief:
        return brief(args.slug)

    if args.slug:
        slugs = [args.slug]
    else:
        slugs = sorted(p.parent.name for p in SKILLS.glob("*/handfixes.json"))

    checked = 0
    all_failures: list[str] = []
    for slug in slugs:
        if not (SKILLS / slug).is_dir():
            print(f"warning: skills/{slug} not found; skipping", file=sys.stderr)
            continue
        fails = check_skill(slug)
        if (SKILLS / slug / "handfixes.json").exists():
            checked += 1
        all_failures.extend(fails)

    if all_failures:
        print("FAIL: hand-fix ledger regressions (a reprint may have clobbered a live-validated fix):\n")
        for f in all_failures:
            print(f"  - {f}")
        print("\nSee docs/reprint-survival.md for how the ledger + this gate work.")
        return 1

    if checked == 0:
        print("PASS: no hand-fix ledgers to check.")
    else:
        print(f"PASS: hand-fix ledgers intact for {checked} skill(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
