#!/usr/bin/env python3
"""Generate .coderabbit.yaml: keep untouched press template output out of CodeRabbit's review.

    python3 tools/maintainer/gen_coderabbit_config.py            # write .coderabbit.yaml
    python3 tools/maintainer/gen_coderabbit_config.py --check    # CI: fail if it is stale
    python3 tools/maintainer/gen_coderabbit_config.py --stats    # what is excluded, and why
    python3 tools/maintainer/gen_coderabbit_config.py --self-test

Why
---
CodeRabbit skips any pull request over 100 files ("Review skipped: N files
exceed the limit of 100") and says nothing else, so a connector pull request
gets a green CodeRabbit status and no review at all. Most of those files are Go
the press generated and nobody edited. `reviews.path_filters` keeps files out
of the review and, measured on PR #417, out of the count.

What is excluded, and what never is
-----------------------------------
Excluded: a regular `.go` file under `skills/<slug>/` whose header (the lines
before its `package` clause) carries the press's own DO-NOT-EDIT line, and that
its connector's `handfixes.json` does not name in any assert.

Never excluded: every generated file `handfixes.json` names (a hand-fix lives
there), every spec, every hand-written file, and everything outside `skills/`.
That is structural, not a promise: every emitted pattern ends in `.go`, so no
spec, ledger, doc or JSON file can match one, and before writing, every pattern
is checked against every file that must stay in review under the most
permissive reading of a glob any matcher could apply (`*` crossing `/`, case
ignored). A pattern that could reach such a file is a bug: the run fails and
writes nothing.

Why exclusions only
-------------------
CodeRabbit's documented rules: an exclusion (`!pattern`) wins regardless of
order, and any pattern without `!` turns the list into an allowlist. So a
directory cannot be excluded and a hand-fixed file inside it re-included. Each
exclusion must cover only untouched template output, at the coarsest shape
that still does: a whole subtree of Go files where every Go file in it is
untouched, one path shared by many connectors' templates, or a file-name
prefix within one connector's directory cut at a word boundary (`_`, `-`, `.`),
so it extends an existing generated resource family rather than catching any
name that happens to start with the same letter. Per-file entries for the
fleet would be about 25,000 lines.

`inheritance: true` is required: CodeRabbit does not merge configuration
sources by default, so a repository file with only `path_filters` would reset
every Organization UI setting to the schema defaults.

Residuals, stated so nobody assumes more
----------------------------------------
* A hand-edit to a generated file that was never recorded in `handfixes.json`
  reads as untouched and is excluded. The ledger is the contract
  (check_handfixes.py --discover lists connectors with unrecorded fixes).
* A pattern can cover a file that does not exist yet. If a pull request adds a
  hand-written file, or a hand-fix, that an existing pattern covers, this
  file's drift check fails on that pull request (the regenerated scope differs)
  until it is regenerated. If CodeRabbit reads the configuration from main
  rather than from the pull request's branch (PR #417 measured the
  Organization UI layer and no repository file), main's patterns apply to that
  one pull request, so CodeRabbit does not see that file there.

Pure stdlib, no local imports (it runs under `python3 -I`).
"""

