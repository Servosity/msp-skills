GEN = HEADER_LINES[0]


def _write(root: Path, rel: str, text: str) -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def _gen_go(pkg: str = "cli", extra: str = "") -> str:
    return f"// Copyright 2026 Example\n{GEN}\n\npackage {pkg}\n{extra}"


def _fixture(root: Path) -> None:
    subprocess.run(["git", "init", "-q", str(root)], check=True)
    for slug in ("acme", "beta"):
        base = f"skills/{slug}/cli"
        _write(root, f"{base}/internal/cli/helpers.go", _gen_go())                  # shared template path
        _write(root, f"{base}/internal/types/types.go", _gen_go("types"))           # pure subtree
        _write(root, f"{base}/internal/types/more/deep.go", _gen_go("more"))
        family = "widgets" if slug == "acme" else "gadgets"                          # a resource family
