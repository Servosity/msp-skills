OUTPUT = ".coderabbit.yaml"
SKILLS = "skills"
# The press writes one of these lines, alone, in the header comment of every
# file it generates (measured: 25,831 and 7,014 files on main, every one before
# the `package` clause).
HEADER_LINES = (
    "// Generated by CLI Printing Press (https://github.com/mvanhorn/cli-printing-press). DO NOT EDIT.",
    "// Code generated by CLI Printing Press. DO NOT EDIT.",
)
# Characters a path may contain to appear in a pattern verbatim. Anything else
# (a glob metacharacter, a quote, a space, non-ASCII) could be read as syntax by
# some matcher or YAML parser, so such a file is simply never excluded.
_SAFE_PATH = re.compile(r"[A-Za-z0-9._/-]+")
_PACKAGE = re.compile(r"package\s")
# A subtree pattern must stay inside one connector's cli/ tree.
_MIN_SUBTREE_DEPTH = 4  # skills/<slug>/cli/<dir>
_BOUNDARY = "_-."
MIN_CROSS = 2  # a shared-template pattern must name a path at least two connectors carry

HEADER_TEXT = """\
# CodeRabbit review scope. GENERATED by tools/maintainer/gen_coderabbit_config.py:
# do not edit by hand. Regenerate and commit:
#   python3 tools/maintainer/gen_coderabbit_config.py
# CI (tools/maintainer/ci_guards.sh) fails when this file is not what the
# generator writes for the tree.
#
# Excluded: Go files under skills/ that carry the cli-printing-press DO-NOT-EDIT
# header and that their connector's handfixes.json does not name (untouched
# template output). Always reviewed: every hand-fixed generated file, every
# spec, every hand-written file. Every pattern ends in .go and is checked
# against every file that must stay in review before this file is written.
#
# Exclusions only: CodeRabbit applies a "!" pattern regardless of order, and a
# pattern without "!" would turn this list into an allowlist.
# inheritance: true keeps the Organization UI settings; without it, this file
# would reset every one of them to the schema defaults.
"""


class GenError(Exception):
    """The scope cannot be established; nothing is written."""


@dataclass
class Scope:
    excluded: set[str] = field(default_factory=set)  # untouched template output
    kept: set[str] = field(default_factory=set)      # everything else under skills/
    reasons: dict[str, int] = field(default_factory=dict)

    def keep(self, path: str, why: str) -> None:
        self.kept.add(path)
        self.reasons[why] = self.reasons.get(why, 0) + 1


# --------------------------------------------------------------------------- #
# The tree
# --------------------------------------------------------------------------- #
def tree_files(root: Path) -> list[str]:
    """Every path a commit would carry, in the WHOLE repository: tracked files
    still on disk plus untracked files git does not ignore (the same set
    ci_guards.sh and verify_all.sh check). A tracked file missing from disk is
    skipped. Every path is part of the safety check, so one that cannot be
    read as UTF-8 fails the run instead of silently leaving it."""
    p = subprocess.run(["git", "-C", str(root), "-c", "core.quotePath=false", "ls-files", "-z", "--cached",
                        "--others", "--exclude-standard"], capture_output=True, timeout=300)
    if p.returncode != 0:
        raise GenError(f"git ls-files failed: {p.stderr.decode('utf-8', 'replace').strip()[-400:]}")
    out = set()
    for raw in p.stdout.split(b"\0"):
        if not raw:
            continue
        try:
            path = raw.decode("utf-8")
        except UnicodeDecodeError:
            raise GenError(f"a path is not UTF-8 ({raw!r}): which files it would hide cannot be checked; rename it")
        try:
            os.lstat(root / path)
        except FileNotFoundError:
            continue
        except OSError as exc:
            raise GenError(f"cannot stat {path}: {exc}")
        out.add(path)
    return sorted(out)


def handfix_files(root: Path, slug: str) -> set[str]:
    """Repo paths of every file this connector's handfixes.json names. An
    unreadable or malformed ledger fails the run: without it, which generated
    files carry a hand-fix cannot be known."""
    ledger = root / SKILLS / slug / "handfixes.json"
    if not ledger.exists():
        return set()
    if ledger.is_symlink() or not ledger.is_file():
        raise GenError(f"{ledger.relative_to(root)} is not a regular file")
    try:
        data = json.loads(ledger.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise GenError(f"cannot read {ledger.relative_to(root)}: {exc}")
    fixes = data.get("handfixes") if isinstance(data, dict) else None
    if not isinstance(fixes, list):
        raise GenError(f"{ledger.relative_to(root)}: no 'handfixes' list")
    out = set()
    for i, fix in enumerate(fixes):
        asserts = fix.get("asserts") if isinstance(fix, dict) else None
        if not isinstance(asserts, list):
            raise GenError(f"{ledger.relative_to(root)}: handfixes[{i}] has no 'asserts' list")
        for a in asserts:
            f = a.get("file") if isinstance(a, dict) else None
            if not isinstance(f, str) or not f:
                raise GenError(f"{ledger.relative_to(root)}: handfixes[{i}] has an assert without a 'file'")
            out.add(os.path.normpath(f"{SKILLS}/{slug}/{f}").replace(os.sep, "/").lower())
    return out


_HEADER_SCAN_LIMIT = 64 * 1024  # the press header sits in the first few lines


def has_press_header(path: Path) -> bool:
    """True when one of HEADER_LINES is a `//` comment standing alone on its
    line in the comments that open the file, and the first thing after those
    comments is the `package` clause. Read lexically, the way Go reads it:
    any token that is not whitespace or a comment ends the header, so text
    after `package` (even on the same line), inside a `/* */` block, or after
    other text on its line is never the header. Anything unexpected (an
    unterminated block comment, no package clause) reads as hand-written,
    which keeps the file in review."""
    try:
        with path.open("rb") as fh:
            text = fh.read(_HEADER_SCAN_LIMIT).decode("utf-8", errors="replace")
    except OSError as exc:
        raise GenError(f"cannot read {path}: {exc}")
    i, n, found, line_start = 0, len(text), False, True
    if text.startswith("\ufeff"):
        i = 1
    while i < n:
        c = text[i]
        if c == "\n":
            i, line_start = i + 1, True
        elif c in " \t\r\f\v":
            i += 1
        elif text.startswith("//", i):
            end = text.find("\n", i)
            end = n if end < 0 else end
            if line_start and text[i:end].strip() in HEADER_LINES:
                found = True
            i, line_start = end, False
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            if end < 0:
                return False
            i, line_start = end + 2, False
        else:
            return found and _PACKAGE.match(text, i) is not None
    return False


def _named_in(path: str, ledger: set[str]) -> bool:
    """A ledger names a file by its exact path; matched ignoring case (a
    case-blind file system resolves "Root.go" to root.go, so the gate would
    pass) and as a directory prefix. Both only ever keep more in review."""
    low = path.lower()
    return any(low == e or low.startswith(e.rstrip("/") + "/") for e in ledger)


def classify(root: Path, files: list[str] | None = None) -> Scope:
    files = tree_files(root) if files is None else files
    scope = Scope()
    ledgers: dict[str, set[str]] = {}
    for path in files:
        parts = path.split("/")
        if len(parts) < 3 or parts[0] != SKILLS:
            # Never excluded, and still checked against every pattern: under a
            # case-blind matcher "Skills/..." could otherwise slip past.
            scope.keep(path, "outside skills/")
            continue
        slug = parts[1]
        if slug not in ledgers:
            ledgers[slug] = handfix_files(root, slug)
        st = os.lstat(root / path)
        if not stat.S_ISREG(st.st_mode):
            scope.keep(path, "not a regular file")
        elif not path.endswith(".go"):
            scope.keep(path, "not Go")
        elif _named_in(path, ledgers[slug]):
            scope.keep(path, "named in handfixes.json")
        elif not has_press_header(root / path):
            scope.keep(path, "no press header (hand-written)")
        elif not _SAFE_PATH.fullmatch(path):
            scope.keep(path, "path has characters a pattern cannot carry verbatim")
        else:
            scope.excluded.add(path)
    for path in sorted(twins(scope.excluded, scope.kept)):
        scope.excluded.discard(path)
        scope.keep(path, "same path as a file that stays in review, ignoring case or from another directory")
    return scope


def _views(path: str) -> list[str]:
    """`path` lowercased, read from the root and from every "/" (how a
    case-blind or unanchored matcher could see it)."""
    low = path.lower()
    return [low] + [low[j + 1:] for j, ch in enumerate(low) if ch == "/"]


def twins(excluded: set[str], kept: set[str]) -> set[str]:
    """Excluded paths no pattern can cover without also matching a kept file:
    the same path ignoring case, or a kept path that ends in it after a "/".
    Even an exact pattern would hide that kept file, so these stay in review."""
    seen = {v for k in kept for v in _views(k)}
    return {p for p in excluded if p.lower() in seen}


# --------------------------------------------------------------------------- #
# Glob semantics
# --------------------------------------------------------------------------- #
def permissive_re(pattern: str) -> re.Pattern:
    """The widest reading any glob matcher could give the shapes this tool
    emits: every `*` and `**` (and `**/`) crosses `/`, and case is ignored. A
    file that this does not match, no stricter matcher matches either."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append(".*")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append(".*")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out), re.IGNORECASE | re.DOTALL)


def strict_re(pattern: str) -> re.Pattern:
    """minimatch / gitignore reading: `**/` is zero or more whole segments,
    `*` never crosses `/`, case matters. Used to prove each excluded file is
    really covered (the patterns are not malformed)."""
    out, i = [], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:[^/]+/)*")
            i += 3
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out))


def _literal_prefix(pattern: str) -> str:
    return pattern.split("*", 1)[0]


def _in_prefix(sorted_items: list[str], prefix: str) -> list[str]:
    lo = bisect.bisect_left(sorted_items, prefix)
    out = []
    for i in range(lo, len(sorted_items)):
        if not sorted_items[i].startswith(prefix):
            break
        out.append(sorted_items[i])
    return out


# --------------------------------------------------------------------------- #
# Patterns
# --------------------------------------------------------------------------- #
def _lcp(a: str, b: str) -> int:
    n, i = min(len(a), len(b)), 0
    while i < n and a[i] == b[i]:
        i += 1
    return i


def build_patterns(scope: Scope) -> list[str]:
    """The exclusion patterns, coarsest first. Construction may be
    conservative; `verify` is the authority on safety and coverage."""
    # Every kept Go path, lowercased, read from the root and from every "/"
    # (the readings verify() applies); only views starting with "skills/" can
    # meet a pattern.
    views = {v for p in scope.kept if p.lower().endswith(".go") for v in _views(p) if v.startswith(SKILLS + "/")}
    kgo = sorted(views)
    # Only a path that starts with "skills/" in some case can match a pattern;
    # the text after it is what a cross-connector "*" can reach.
    kgo_tail = [k[len(SKILLS):] for k in kgo if k.startswith(SKILLS + "/")]

    def pure_dir(d: str) -> bool:  # no kept Go file anywhere under d
        return not _in_prefix(kgo, d.lower() + "/")

    patterns: set[str] = set()
    covered: set[str] = set()
    by_slug: dict[str, list[str]] = {}
    for p in sorted(scope.excluded):
        by_slug.setdefault(p.split("/")[1], []).append(p)

    # A. Whole subtrees of Go files. Maximal pure directories per connector,
    # then shared across connectors where every connector's copy is pure.
    subtree: dict[str, set[str]] = {}  # rel dir -> slugs
    for slug, paths in by_slug.items():
        for p in paths:
            parts = p.split("/")
            best = None
            for depth in range(_MIN_SUBTREE_DEPTH, len(parts)):
                d = "/".join(parts[:depth])
                if pure_dir(d):
                    best = d
                    break
            if best is not None:
                subtree.setdefault("/".join(best.split("/")[2:]), set()).add(slug)
    for rel, slugs in subtree.items():
        needle = "/" + rel.lower() + "/"
        if len(slugs) >= MIN_CROSS and not any(needle in t for t in kgo_tail):
            patterns.add(f"{SKILLS}/*/{rel}/**/*.go")
            for slug in by_slug:
                covered.update(p for p in by_slug[slug] if p.startswith(f"{SKILLS}/{slug}/{rel}/"))
        else:
            for slug in sorted(slugs):
                patterns.add(f"{SKILLS}/{slug}/{rel}/**/*.go")
                covered.update(p for p in by_slug[slug] if p.startswith(f"{SKILLS}/{slug}/{rel}/"))

    # B. One path that many connectors' templates share, every copy untouched.
    rels: dict[str, set[str]] = {}
    for p in scope.excluded - covered:
        rels.setdefault("/".join(p.split("/")[2:]), set()).add(p.split("/")[1])
    for rel, slugs in rels.items():
        if len(slugs) < MIN_CROSS:
            continue
        tail = "/" + rel.lower()
        if any(t.endswith(tail) for t in kgo_tail):
            continue
        patterns.add(f"{SKILLS}/*/{rel}")
        covered.update(f"{SKILLS}/{s}/{rel}" for s in slugs)
        covered.update(p for p in scope.excluded if p.endswith("/" + rel) and p.split("/", 2)[2] == rel)

    # C. The rest, one connector directory at a time: the shortest word-
    # boundary prefix no kept Go file under that directory shares, else the
    # exact path.
    groups: dict[str, list[str]] = {}
    for p in sorted(scope.excluded - covered):
        d, name = p.rsplit("/", 1)
        groups.setdefault(d, []).append(name)
    for d, names in groups.items():
        tails = sorted(k[len(d) + 1:] for k in _in_prefix(kgo, d.lower() + "/"))
        for name in names:
            low = name.lower()
            j = bisect.bisect_left(tails, low)
            need = 1 + max([_lcp(low, t) for t in tails[max(0, j - 1):j + 1]] or [0])
            stem = name[:-3]
            cut = next((i for i in range(need, len(stem) + 1) if i == len(stem) or stem[i] in _BOUNDARY), None)
            if cut is not None:
                patterns.add(f"{d}/{stem[:cut]}*.go")
            else:
                # classify() moved every case-only or unanchored twin of a kept
                # file to kept, so the exact path is safe; verify() re-checks.
                patterns.add(f"{d}/{name}")
    return sorted(patterns)


def verify(patterns: list[str], scope: Scope) -> list[str]:
    """Problems that make the pattern list unsafe or wrong; empty when sound.
    (1) Every pattern is in the emitted subset: under skills/, ends in .go,
    only path characters and '*'. (2) No kept file matches any pattern under
    the permissive reading. (3) Every excluded file matches some pattern under
    the strict reading."""
    problems: list[str] = []
    for pat in patterns:
        if not pat.startswith(SKILLS + "/") or not pat.endswith(".go") or not re.fullmatch(r"[A-Za-z0-9._/*-]+", pat):
            problems.append(f"pattern outside the emitted subset: {pat!r}")
    if problems:
        return problems
    # Every pattern ends in .go (checked above), so only a kept path ending in
    # .go, in any case, can match. A matcher might also not anchor a pattern
    # at the repository root, so each kept path is tried from every "/" too.
    views = sorted((v, p) for p in scope.kept if p.lower().endswith(".go") for v in _views(p))
    keys = [v for v, _p in views]
    for pat in patterns:
        rx = permissive_re(pat)
        lit = _literal_prefix(pat).lower()
        lo = bisect.bisect_left(keys, lit)
        for i in range(lo, len(keys)):
            if not keys[i].startswith(lit):
                break
            if rx.fullmatch(keys[i]):
                problems.append(f"{pat} would hide {views[i][1]}, which must stay in review")
    by_rest: dict[str, list[str]] = {}
    for p in scope.excluded:
        by_rest.setdefault(p.split("/", 2)[2], []).append(p)
    rests = sorted(by_rest)
    excluded = sorted(scope.excluded)
    matched: set[str] = set()
    for pat in patterns:
        rx = strict_re(pat)
        if pat.startswith(SKILLS + "/*/"):
            tail = pat[len(SKILLS) + 3:]
            for rest in _in_prefix(rests, _literal_prefix(tail)):
                matched.update(p for p in by_rest[rest] if rx.fullmatch(p))
        else:
            matched.update(p for p in _in_prefix(excluded, _literal_prefix(pat)) if rx.fullmatch(p))
    missing = sorted(scope.excluded - matched)
    if missing:
        problems.append(f"{len(missing)} untouched generated file(s) no pattern covers, e.g. {missing[:3]}")
    return problems


def render(patterns: list[str]) -> str:
    lines = [HEADER_TEXT, "inheritance: true", "reviews:", "  path_filters:" + ("" if patterns else " []")]
    lines += [f'    - "!{p}"' for p in patterns]
    return "\n".join(lines) + "\n"


def generate(root: Path) -> tuple[str, Scope, list[str]]:
    scope = classify(root)
    patterns = build_patterns(scope)
    problems = verify(patterns, scope)
    if problems:
        raise GenError("refusing to write a scope that is wrong:\n  " + "\n  ".join(problems[:20]))
    return render(patterns), scope, patterns


def repo_root(start: Path) -> Path:
    p = subprocess.run(["git", "-C", str(start), "rev-parse", "--show-toplevel"], capture_output=True, text=True,
                       timeout=60)
    if p.returncode != 0:
        raise GenError(f"not inside a git checkout: {p.stderr.strip()}")
    return Path(p.stdout.strip())


def cmd_check(root: Path, out=print) -> int:
    want, _scope, _ = generate(root)
    target = root / OUTPUT
    if target.is_symlink() or (target.exists() and not target.is_file()):
        out(f"FAIL: {OUTPUT} is not a regular file")
        return 1
    raw = target.read_bytes() if target.is_file() else None
    have = raw.decode("utf-8", errors="replace") if raw is not None else None
    if raw == want.encode("utf-8"):
        out(f"OK: {OUTPUT} matches the generator ({want.count(chr(10) + '    - ')} exclusion patterns)")
        return 0
    out(f"FAIL: {OUTPUT} is {'missing' if have is None else 'stale'}: it is not what the generator writes for "
        "this tree, so CodeRabbit would review a different set of files than the rules say.")
    if have is not None:
        diff = list(difflib.unified_diff(have.splitlines(), want.splitlines(), f"{OUTPUT} (committed)",
                                         f"{OUTPUT} (generated)", n=0, lineterm=""))
        for line in diff[:40]:
            out("  " + line)
        if len(diff) > 40:
            out(f"  ... {len(diff) - 40} more diff lines")
    out("  fix: python3 tools/maintainer/gen_coderabbit_config.py && git add .coderabbit.yaml")
    return 1


def cmd_stats(root: Path) -> int:
    _text, scope, patterns = generate(root)
    kinds = {"subtree": sum(p.endswith("/**/*.go") for p in patterns),
             "shared template path": sum(p.startswith(SKILLS + "/*/") and "*" not in p[len(SKILLS) + 3:]
                                         for p in patterns),
             "prefix": sum("*" in p and not p.endswith("/**/*.go") and not p.startswith(SKILLS + "/*/")
                           for p in patterns)}
    kinds["exact"] = len(patterns) - sum(kinds.values())
    print(json.dumps({"excluded_files": len(scope.excluded), "kept_files": len(scope.kept),
                      "kept_by_reason": dict(sorted(scope.reasons.items())), "patterns": len(patterns),
                      "patterns_by_kind": kinds}, indent=2))
    return 0


