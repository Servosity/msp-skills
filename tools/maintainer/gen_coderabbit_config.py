def _self_test() -> int:
    results: list[tuple[bool, str]] = []

    def expect(ok: bool, label: str) -> None:
        results.append((bool(ok), label))

    def matched(patterns: list[str], path: str, how=strict_re) -> bool:
        return any(how(p).fullmatch(path) for p in patterns)

    def quiet(_line: str) -> None:
        pass

    tmp = Path(tempfile.mkdtemp(prefix="gen-coderabbit-selftest-"))
    try:
        root = tmp / "repo"
        _fixture(root)
        text, scope, pats = generate(root)
        kept_must = ["skills/acme/cli/internal/cli/root.go", "skills/acme/cli/internal/cli/novel_report.go",
                     "skills/acme/cli/internal/cli/late_header.go", "skills/acme/cli/internal/cli/mention.go",
                     "skills/acme/press/spec.yaml", "skills/acme/press/spec.json", "skills/acme/handfixes.json",
                     "skills/acme/cli/go.mod", "skills/acme/README.md"]
        for k in kept_must:
            expect(k in scope.kept and not matched(pats, k, permissive_re), f"kept and unmatched: {k}")
        expect(not matched(pats, "tools/x.go", permissive_re), "a generated file outside skills/ is never excluded")
        for e in ("skills/acme/cli/internal/cli/helpers.go", "skills/beta/cli/internal/cli/root.go",
                  "skills/acme/cli/internal/types/more/deep.go", "skills/acme/cli/internal/cli/widgets_get.go"):
            expect(e in scope.excluded and matched(pats, e), f"excluded and matched: {e}")
        expect("skills/*/cli/internal/cli/helpers.go" in pats, "a template path every connector shares is one pattern")
        expect("skills/*/cli/internal/types/**/*.go" in pats, "a pure subtree is one pattern")
        expect("skills/acme/cli/internal/cli/widgets*.go" in pats, "a resource family is one prefix pattern")
        expect(not any(p.startswith("skills/*/cli/internal/cli/root") for p in pats),
               "a template path hand-fixed in one connector gets no shared pattern")
        expect(all(p.endswith(".go") for p in pats), "every pattern ends in .go")
        expect(text.startswith("# CodeRabbit review scope") and "\ninheritance: true\n" in text
               and all(ord(c) < 128 for c in text), "header, inheritance: true, ASCII only")
        expect(all(line.startswith('    - "!skills/') for line in text.splitlines() if line.startswith("    - ")),
               "every entry is a quoted exclusion")
        expect(generate(root)[0] == text, "deterministic")

        # Writing and --check, both directions.
        (root / OUTPUT).write_text(text, encoding="utf-8")
        expect(cmd_check(root, quiet) == 0, "--check passes on a fresh file")
        edited = text.replace('"!skills/*/cli/internal/cli/helpers.go"', '"!skills/*/cli/internal/cli/*.go"')
        expect(edited != text, "(setup) the edit changes the file")
        (root / OUTPUT).write_text(edited, encoding="utf-8")
        expect(cmd_check(root, quiet) == 1, "--check fails on an edited file")
        (root / OUTPUT).unlink()
        expect(cmd_check(root, quiet) == 1, "--check fails on a missing file")
        (root / OUTPUT).write_text(text, encoding="utf-8")

        # A new hand-fix recorded in the ledger makes the committed file stale,
        # and the regenerated scope keeps that file in review.
        led = root / "skills/beta/handfixes.json"
        led.write_text(json.dumps({"slug": "beta", "handfixes": [{"id": "w", "asserts": [
            {"file": "cli/internal/cli/gadgets_get.go", "contains": "x"}]}]}) + "\n", encoding="utf-8")
        expect(cmd_check(root, quiet) == 1, "a new hand-fix makes the committed scope stale")
        _t2, _s2, p2 = generate(root)
        expect(not matched(p2, "skills/beta/cli/internal/cli/gadgets_get.go", permissive_re)
               and matched(p2, "skills/beta/cli/internal/cli/gadgets_list.go"),
               "the regenerated scope reviews the hand-fixed file and still excludes its untouched sibling")
        led.write_text(json.dumps({"slug": "beta", "handfixes": []}) + "\n", encoding="utf-8")

        # A new hand-written file that an existing prefix pattern would cover.
        prefix_pat = "skills/acme/cli/internal/cli/widgets*.go"
        newfile = "skills/acme/cli/internal/cli/widgets_summary.go"
        expect(matched([prefix_pat], newfile), f"(setup) {prefix_pat} covers the new name")
        _write(root, newfile, "package cli\n")
        expect(cmd_check(root, quiet) == 1, "a new hand-written file under a prefix pattern makes the scope stale")
        _t3, _s3, p3 = generate(root)
        expect(not matched(p3, newfile, permissive_re), "the regenerated scope reviews the new hand-written file")
        (root / newfile).unlink()

        # Case-insensitive and slash-crossing readings are guarded.
        # A case-only or unanchored twin of a kept file: no pattern can cover
        # it without hiding the kept one, so it stays in review. Proved as a
        # pure function on every OS, and on disk where the file system can
        # hold both names (CI's Linux; a case-blind disk merges them).
        ex = {"skills/acme/cli/internal/cli/zones.go", "skills/acme/cli/internal/cli/widgets_get.go"}
        expect(twins(ex, {"skills/acme/cli/internal/cli/ZONES.GO"}) == {"skills/acme/cli/internal/cli/zones.go"}
               and twins(ex, {"vendor/skills/acme/cli/internal/cli/zones.go"})
               == {"skills/acme/cli/internal/cli/zones.go"} and not twins(ex, {"skills/acme/README.md"}),
               "twins(): a kept path equal ignoring case, or ending in the path after a '/', keeps it in review")
        _write(root, "vendor/skills/acme/cli/internal/cli/zones.go", "package cli\n")
        _t4, s4, p4 = generate(root)
        expect("skills/acme/cli/internal/cli/zones.go" in s4.kept
               and not matched(p4, "skills/acme/cli/internal/cli/zones.go", permissive_re)
               and matched(p4, "skills/beta/cli/internal/cli/zones.go"),
               "on disk: a twin under another directory keeps the generated file in review, and generation succeeds")
        shutil.rmtree(root / "vendor")
        probe = root / "case-probe"
        probe.write_text("x", encoding="utf-8")
        case_blind = (root / "CASE-PROBE").exists()
        probe.unlink()
        if case_blind:
            print("  skip a case-only twin on disk (this file system is case-insensitive; the pure case above covers it)")
        else:
            _write(root, "skills/acme/cli/internal/cli/ZONES.GO", "package cli\n")
            _t9, s9, p9 = generate(root)
            expect("skills/acme/cli/internal/cli/zones.go" in s9.kept
                   and not matched(p9, "skills/acme/cli/internal/cli/ZONES.GO", permissive_re)
                   and not matched(p9, "skills/acme/cli/internal/cli/zones.go", permissive_re)
                   and matched(p9, "skills/beta/cli/internal/cli/zones.go"),
                   "on disk: a case-only twin of a kept file keeps both in review, and generation succeeds")
            (root / "skills/acme/cli/internal/cli/ZONES.GO").unlink()
        _write(root, "skills/acme/cli/internal/cli/widgets_x/notes.go", "package w\n")
        _t5, _s5, p5 = generate(root)
        expect(not matched(p5, "skills/acme/cli/internal/cli/widgets_x/notes.go", permissive_re),
               "a prefix pattern never reaches a kept file in a subdirectory, even if '*' crosses '/'")
        shutil.rmtree(root / "skills/acme/cli/internal/cli/widgets_x")

        # Codex r1 P1-1: a package clause that does not start its line must
        # still end the header; header text after it is not a header.
        tricky = {
            "block_pkg.go": f"/* handwritten */ package cli\n{HEADER_LINES[1]}\n",
            "header_in_block.go": f"/*\n{GEN}\n*/\npackage cli\n",
            "header_after_code.go": f"/* x */ {GEN}\npackage cli\n",
            "header_after_pkg_same_line.go": f"package cli // {GEN}\n",
        }
        for name, body in tricky.items():
            _write(root, f"skills/acme/cli/internal/cli/{name}", body)
        _t7, s7, p7 = generate(root)
        for name in tricky:
            path = f"skills/acme/cli/internal/cli/{name}"
            expect(path in s7.kept and not matched(p7, path, permissive_re),
                   f"no press header before the package clause: {name} stays in review")
        for name in tricky:
            (root / f"skills/acme/cli/internal/cli/{name}").unlink()
        _write(root, "skills/acme/cli/internal/cli/build_tagged.go",
               f"//go:build linux\n\n/* note */\n// Copyright x\n{GEN}\n\npackage cli\n")
        expect("skills/acme/cli/internal/cli/build_tagged.go" in classify(root).excluded,
               "a build tag and comments before the press header still read as generated")
        (root / "skills/acme/cli/internal/cli/build_tagged.go").unlink()

        # Codex r1 P1-2: a path that is not UTF-8 cannot be classified, so the
        # scope cannot be established: fail closed (it never silently drops).
        blob = subprocess.run(["git", "-C", str(root), "hash-object", "-w", "--stdin"], input=b"package types\n",
                              capture_output=True, check=True).stdout.decode().strip()
        odd = b"skills/acme/cli/internal/types/\xff.go"
        subprocess.run([b"git", b"-C", str(root).encode(), b"update-index", b"--add", b"--cacheinfo",
                        b"100644," + blob.encode() + b"," + odd], check=True)
        try:
            generate(root)
            expect(False, "a tracked path that is not UTF-8 fails the run")
        except GenError:
            expect(True, "a tracked path that is not UTF-8 fails the run")
        subprocess.run([b"git", b"-C", str(root).encode(), b"update-index", b"--force-remove", odd], check=True)

        # A ledger entry differing only in case, or naming a directory, keeps the file.
        led.write_text(json.dumps({"slug": "beta", "handfixes": [{"id": "c", "asserts": [
            {"file": "cli/internal/cli/GADGETS_GET.go", "contains": "x"},
            {"file": "cli/internal/types/more", "contains": "x"}]}]}) + "\n", encoding="utf-8")
        s8 = classify(root)
        expect("skills/beta/cli/internal/cli/gadgets_get.go" in s8.kept
               and "skills/beta/cli/internal/types/more/deep.go" in s8.kept,
               "a ledger path matching only ignoring case, or naming a directory, keeps the file in review")
        led.write_text(json.dumps({"slug": "beta", "handfixes": []}) + "\n", encoding="utf-8")
        # A matcher that does not anchor at the repository root.
        unanchored = Scope(excluded=set(scope.excluded),
                           kept=set(scope.kept) | {"vendor/skills/acme/cli/internal/cli/widgets_new.go"})
        expect(any("would hide vendor/skills/acme" in x for x in verify(pats, unanchored)),
               "verify also reads each pattern unanchored (a kept path under another directory)")
        expect(not verify(build_patterns(unanchored), unanchored),
               "and pattern construction avoids what that reading would hide")
        # --check compares bytes: a CRLF copy of the right text is not the file.
        (root / OUTPUT).write_bytes(text.replace("\n", "\r\n").encode("utf-8"))
        expect(cmd_check(root, quiet) == 1, "--check compares bytes (a CRLF rewrite is stale)")
        (root / OUTPUT).write_text(text, encoding="utf-8")

        # A path a pattern cannot carry verbatim stays in review.
        _write(root, "skills/acme/cli/internal/cli/odd[1].go", _gen_go())
        s6 = classify(root)
        expect("skills/acme/cli/internal/cli/odd[1].go" in s6.kept, "a glob-metacharacter path is never excluded")
        (root / "skills/acme/cli/internal/cli/odd[1].go").unlink()

        empty = render([])
        expect("  path_filters: []\n" in empty, "an empty scope renders as an empty list, not null")

        # The verifier itself fails on a planted bad pattern (the check can fail).
        expect(any("would hide" in x for x in verify(pats + ["skills/*/cli/internal/cli/*.go"], scope)),
               "verify rejects a pattern that hides a hand-fixed or hand-written file")
        expect(any("outside the emitted subset" in x for x in verify(pats + ["skills/acme/press/*"], scope)),
               "verify rejects a pattern that does not end in .go")
        expect(any("no pattern covers" in x for x in verify(pats[1:], scope)),
               "verify rejects a list that leaves an untouched generated file uncovered")

        # A malformed ledger fails closed: nothing is written.
        led.write_text("{not json", encoding="utf-8")
        try:
            generate(root)
            expect(False, "a malformed handfixes.json fails the run")
        except GenError:
            expect(True, "a malformed handfixes.json fails the run")
        led.write_text(json.dumps({"slug": "beta", "handfixes": [{"id": "x", "asserts": [{"contains": "y"}]}]}),
                       encoding="utf-8")
        try:
            generate(root)
            expect(False, "an assert without a file fails the run")
        except GenError:
            expect(True, "an assert without a file fails the run")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    bad = [label for ok, label in results if not ok]
    for ok, label in results:
        print(f"  {'ok  ' if ok else 'FAIL'} {label}")
    print(f"{'PASS' if not bad else 'FAIL'}: gen_coderabbit_config self-test, {len(results) - len(bad)}/{len(results)}")
    return 0 if not bad else 1


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail (exit 1) if .coderabbit.yaml is missing or stale")
    mode.add_argument("--stats", action="store_true", help="print what is excluded and kept, by reason")
    mode.add_argument("--self-test", action="store_true", help="prove the rules both ways on a throwaway repo")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.self_test:
        return _self_test()
    try:
        root = repo_root(args.root)
        if args.check:
            return cmd_check(root)
        if args.stats:
            return cmd_stats(root)
        text, scope, patterns = generate(root)
    except GenError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    target = root / OUTPUT
    if target.is_symlink() or (target.exists() and not target.is_file()):
        print(f"FAIL: {OUTPUT} is not a regular file; refusing to write through it", file=sys.stderr)
        return 2
    tmp = target.with_name(f".{OUTPUT}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, target)
    print(f"wrote {OUTPUT}: {len(patterns)} exclusion patterns covering {len(scope.excluded)} untouched generated "
          f"files; {len(scope.kept)} other files stay in review")
    return 0


if __name__ == "__main__":
    sys.exit(main())
