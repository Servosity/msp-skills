#!/usr/bin/env python3
"""The live-verification badge: flip one skill to "live-verified" or back.

A skill is "live-verified" once a real MSP has run it against a real tenant and
told us it worked - in a Build Session, on Circle, via a GitHub "it works"
report, or by our own dogfooding. That fact lives in the registry under each
skill's "live_verified" key:

    "live_verified": {
      "status": "live-verified" | "awaiting",
      "date": "YYYY-MM-DD",
      "source": "build-session" | "circle" | "github" | "self",
      "evidence": "<url or note>",
      "verified_by": "<who confirmed it, e.g. @handle (MSP)>" | null,
      "issue_url": "<clickable receipt link>" | null,
      "verified_version": "X.Y.Z" | null,
      "verified_cli_hash": "sha256:<hex>" | null,
      "verified_basis": "reported" | "latest-release-at-flip" | "unknown"
    }

The last three bind the badge to the code that was verified: the release
version and the cli_hash.py hash of skills/<dir>/cli at that release's tag
(computed from git objects, exactly as stamp_release.py stamps
cli_hash_at_release). The catalog then shows "verified on vX.Y.Z" once the
shipped release carries different code, so a badge never silently covers code
no MSP ran. The basis says how the version was chosen:
  reported                the reporter named it (--verified-version)
  latest-release-at-flip  the newest release tag at the flip, skipping any
                          cut from a commit made after the report
                          (--reported-at); what a fresh install gave them
  unknown                 nothing provable (both fields null)
`--bind` sets these on an existing badge without touching its date or
evidence (the backfill path, and a report that names its version later).

A skill without the key is treated as "awaiting" - tools tolerate its absence.
`verified_by` and `issue_url` are what the catalog + per-skill page actually
render (the attribution line and the "receipt ->" link); pass --verified-by /
--issue-url to set them. For a `--source github` flip whose --evidence is a
github.com URL, issue_url defaults to that URL so the receipt link is never
silently dropped (the gap that left sentinelone #116 reading "by Servosity
(maintainer)" with no receipt).

This is a DOCS-ONLY flip. It changes skills.json (which the catalog + per-skill
pages render from); it does NOT cut a release or push a tag. After a flip,
regenerate the catalog and commit.

Beta and live-verified are mutually exclusive. A flip also sets the registry
"status" to "live-verified" and rewrites the first paragraph under "## Status"
in skills/<dir>/README.md and pain-point.md; a revoke puts both back to Beta.
An existing "Live-verified ..." paragraph is kept as written, so hand-written
receipt detail survives a --force re-flip. --check (run in CI) fails on any
skill where the registry, a Status section (of the README, the pain-point or
the generated docs page) or a stray "Beta" disagrees with the badge. Pages are
read as they render: any heading form, entities decoded, emphasis dropped.
--sync repairs the registry and the two hand-written Status paragraphs; the
docs page is regenerated by build-catalog.py, and a stray "Beta" elsewhere is
left for a person to edit. Before
2026-10-23 nothing tied them together, and all 19 live-verified connectors
still said Beta (first fixed in #354, which never merged).

Usage:
    python3 tools/maintainer/verify_live.py --slug halopsa --source build-session \\
        --evidence "https://circle.so/..." [--date 2026-06-04]
    python3 tools/maintainer/verify_live.py --slug cove --source github \\
        --evidence "https://github.com/Servosity/msp-skills/issues/139" \\
        --verified-by "@AvlCompCo (MSP)"   # issue_url defaults from --evidence
    python3 tools/maintainer/verify_live.py --revoke --slug halopsa
    python3 tools/maintainer/verify_live.py --bind --slug cove --verified-version 0.1.3
    python3 tools/maintainer/verify_live.py --bind --slug cove --unknown
    python3 tools/maintainer/verify_live.py --status
    python3 tools/maintainer/verify_live.py --check       # exit 1 on Beta/verified drift
    python3 tools/maintainer/verify_live.py --sync        # repair that drift
    python3 tools/maintainer/verify_live.py --self-test
    python3 tools/maintainer/verify_live.py --slug halopsa --source self \\
        --evidence "redogfood" --force

Pure stdlib.
"""

from __future__ import annotations

import datetime as dt
import html
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import registry  # noqa: E402  (local tools/ module)
import check_registry_state  # noqa: E402  (local tools/ module: the hash of a tagged tree)
import release_state  # noqa: E402  (local tools/ module: one version order)
from render_docs_page import attribution  # noqa: E402  (one attribution rule for page and prose)

ROOT = registry.ROOT
REGISTRY = registry.REGISTRY

VALID_SOURCES = ("build-session", "circle", "github", "self")

AWAITING = {"status": "awaiting", "date": None, "source": None, "evidence": None}

BASES = ("reported", "latest-release-at-flip", "unknown")
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+\Z")
UNKNOWN_BINDING = {"verified_version": None, "verified_cli_hash": None, "verified_basis": "unknown"}


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True, timeout=60)


def _tag_exists(tag: str) -> bool:
    return _git("rev-parse", "-q", "--verify", f"refs/tags/{tag}").returncode == 0


def tag_cli_hash(slug: str, tag: str) -> str | None:
    """cli_hash.py's hash of the connector's cli/ at `tag`, resolved through the
    tagged commit's own registry (check_registry_state.tag_cli_hash, the rule
    the CI gate re-checks), or None when it cannot be computed."""
    return check_registry_state.tag_cli_hash(slug, {}, tag[len(slug) + 2:])


def _parse_when(value: str) -> dt.datetime:
    try:
        when = dt.datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        raise SystemExit(f"verify_live: --reported-at {value!r} is not an ISO-8601 timestamp")
    if when.tzinfo is None:
        raise SystemExit(f"verify_live: --reported-at {value!r} needs a timezone (e.g. ...Z)")
    return when


def binding(slug: str, version: str | None = None, reported_at: str | None = None) -> dict:
    """The verified_* fields for a flip of `slug` (see the module docstring)."""
    cutoff = _parse_when(reported_at) if reported_at else None

    def after_report(tag: str) -> bool:
        """Cut from a commit made after the report: never what the reporter ran."""
        if cutoff is None:
            return False
        made = _git("log", "-1", "--format=%cI", f"{tag}^{{commit}}").stdout.strip()
        return not made or _parse_when(made) > cutoff

    if version is not None:
        if not VERSION_RE.match(version):
            raise SystemExit(f"verify_live: --verified-version {version!r} is not X.Y.Z")
        tag = f"{slug}-v{version}"
        if not _tag_exists(tag):
            raise SystemExit(f"verify_live: no local tag {tag} (git fetch --tags origin), so "
                             f"the code at {version} cannot be hashed")
        if after_report(tag):
            raise SystemExit(f"verify_live: {tag} was cut from a commit made after the report "
                             f"(--reported-at {reported_at}); the reporter cannot have run it")
        h = tag_cli_hash(slug, tag)
        if h is None:
            raise SystemExit(f"verify_live: {tag} does not release {slug} at {version} in its own "
                             "registry, or its cli/ cannot be hashed reproducibly")
        return {"verified_version": version, "verified_cli_hash": h, "verified_basis": "reported"}
    prefix = f"{slug}-v"
    tags = [t for t in _git("tag", "--list", f"{prefix}*").stdout.split()
            if VERSION_RE.match(t[len(prefix):])]
    for tag in sorted(tags, key=lambda t: release_state._version_tuple(t[len(prefix):]), reverse=True):
        if after_report(tag):
            continue
        h = tag_cli_hash(slug, tag)
        if h is None:
            break
        return {"verified_version": tag[len(prefix):], "verified_cli_hash": h,
                "verified_basis": "latest-release-at-flip"}
    print(f"verify_live: WARNING no release tag of {slug} could be bound (fetch tags?); "
          "recording the verified version as unknown", file=sys.stderr)
    return dict(UNKNOWN_BINDING)


def _read_registry() -> dict:
    """Read through registry.load(), so the identifier grammar is enforced on the
    way in. This script WRITES skills.json back; validating first means it can
    never round-trip a malformed identifier into the file the build matrix reads."""
    return registry.load()


def _write_registry(reg: dict) -> None:
    """Write skills.json preserving 2-space indent, trailing newline, and sorted
    slugs (the repo convention; matches release.py's _write_json + sorted keys)."""
    skills = reg.get("skills", {})
    reg["skills"] = {slug: skills[slug] for slug in sorted(skills)}
    REGISTRY.write_text(json.dumps(reg, indent=2) + "\n", encoding="utf-8")


def _entry_state(entry: dict) -> dict:
    """Return the live_verified sub-dict, defaulting to AWAITING when absent."""
    lv = entry.get("live_verified")
    if not isinstance(lv, dict):
        return dict(AWAITING)
    return lv


# --- Beta and live-verified are mutually exclusive -------------------------

RSVP = "RSVP at [compoundingteams.com/build-sessions](https://compoundingteams.com/build-sessions)."
# The pages a badge must agree with: two hand-written ones under skills/<dir>/
# (--sync rewrites their Status paragraph) and the generated docs page
# (render_docs_page.py writes it; build-catalog.py regenerates it).
STATUS_FILES = ("README.md", "pain-point.md")
BETA = re.compile(r"\bbeta\b", re.I)
LIVE = re.compile(r"\blive[- ]verified\b", re.I)
_MD_ESCAPE = re.compile(r"\\([!-/:-@\[-`{-~])")
_ATX = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?[ \t]*(?:#+[ \t]*)?$")
_SETEXT = re.compile(r"^ {0,3}(=+|-+)[ \t]*$")
_FENCE = re.compile(r"^ {0,3}(```|~~~)")


def _visible(text: str) -> str:
    """The words a reader sees: entities decoded, Markdown escapes and emphasis
    marks dropped, whitespace (newlines included) collapsed. So `**Beta**`,
    `Be&#116;a` and a claim wrapped over two lines all read as their words."""
    t = _MD_ESCAPE.sub(r"\1", html.unescape(text))
    t = re.sub(r"[*_`~]", "", t)
    return re.sub(r"\s+", " ", t).strip()


def _headings(lines: list[str]) -> list[tuple[int, int, str, int]]:
    """(heading line, level, title, first body line) for every ATX heading
    (up to three spaces of indent, optional closing #s) and Setext heading
    (a text line underlined with = or -), skipping fenced code."""
    out: list[tuple[int, int, str, int]] = []
    fence = False
    for i, line in enumerate(lines):
        if _FENCE.match(line):
            fence = not fence
            continue
        if fence:
            continue
        m = _ATX.match(line)
        if m:
            out.append((i, len(m.group(1)), m.group(2) or "", i + 1))
            continue
        if (i + 1 < len(lines) and line.strip() and _SETEXT.match(lines[i + 1])
                and not _SETEXT.match(line)):
            out.append((i, 1 if lines[i + 1].strip().startswith("=") else 2, line.strip(), i + 2))
    return out


def _status_sections(lines: list[str]) -> list[tuple[int, int, int, int]]:
    """For each section headed "Status" (any level): (body start, body end,
    first-paragraph start, first-paragraph end) as line indexes."""
    hs = _headings(lines)
    out = []
    for k, (_, level, title, body) in enumerate(hs):
        if _visible(title).rstrip(":").strip().lower() != "status":
            continue
        end = next((j for (j, lv, _, _) in hs[k + 1:] if lv <= level), len(lines))
        a = body
        while a < end and not lines[a].strip():
            a += 1
        b = a
        while b < end and lines[b].strip() and not _SETEXT.match(lines[b]):
            b += 1
        out.append((body, end, a, b))
    return out


def _verified(entry: dict) -> bool:
    return _entry_state(entry).get("status") == "live-verified"


def _status_para(entry: dict, readme: bool) -> str:
    """The Status paragraph README.md (readme=True) or pain-point.md must carry."""
    if _verified(entry):
        lv = _entry_state(entry)
        receipt = f" ([receipt]({lv['issue_url']}))" if lv.get("issue_url") else ""
        para = f"Live-verified. Confirmed by {attribution(lv)} against their own production tenant{receipt}."
        return para + (f" More MSPs run it live in our weekly Build Sessions. {RSVP}" if readme else "")
    vendor = entry.get("vendor") or entry.get("system") or "vendor"
    if readme:
        return (f"Beta. Validated against the {vendor} API surface and being validated with "
                "MSPs running it live against their own production tenant in our weekly "
                f"Build Sessions. {RSVP}")
    return (f"Beta. Validated against the {vendor} API surface; the closed-loop receipt (a "
            "named MSP running it live in their production tenant at a Build Session) is "
            "tracked separately and added here as `video.md` once it exists.")


def _says_verified(paragraph: str) -> bool:
    return _visible(paragraph).lower().startswith(("live-verified", "live verified"))


def _pages(slug: str, entry: dict, root: Path) -> list[tuple[Path, bool]]:
    """(path, hand-written?) for every page that states the skill's status."""
    d = root / "skills" / str(entry.get("source_dir", slug))
    return [(d / n, True) for n in STATUS_FILES] + [(root / "docs" / "skills" / f"{slug}.md", False)]


def _drift(slug: str, entry: dict, root: Path = ROOT) -> list[str]:
    """Every place this skill claims Beta while verified, or verified while not.

    Verified: "Beta" nowhere in the README, pain-point or docs page (as read,
    so emphasis or an entity cannot hide it), and every Status section opens
    with "Live-verified". Not verified: no Status section claims it. (A
    sentence elsewhere may mention the badge: "a real MSP run is what earns
    the live-verified badge".) A file that exists but cannot be read is drift
    too: unread is not checked."""
    verified = _verified(entry)
    out = []
    if entry.get("markdown_only"):
        return out
    if (entry.get("status") == "live-verified") != verified:
        out.append(f"skills.json status is {entry.get('status')!r} but the badge is "
                   f"{'live-verified' if verified else 'not live-verified'}")
    for p, hand in _pages(slug, entry, root):
        if not p.exists():
            continue
        rel = p.relative_to(root)
        fix = "--sync rewrites it" if hand else "regenerate it with build-catalog.py"
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as e:
            out.append(f"{rel} could not be read ({e})")
            continue
        lines = text.split("\n")
        reported: set[int] = set()
        for (body, end, a, b) in _status_sections(lines):
            para = "\n".join(lines[a:b])
            if verified and not _says_verified(para):
                out.append(f"{rel}:{a + 1} Status says {_visible(para)[:24]!r} ({fix})")
                reported.update(range(a, b))
            if not verified and LIVE.search(_visible("\n".join(lines[body:end]))):
                out.append(f"{rel}:{body + 1} Status claims Live-verified but the badge is not "
                           f"({fix if _says_verified(para) else 'edit it by hand'})")
        rest = "\n".join(ln for i, ln in enumerate(lines) if i not in reported)
        if verified and BETA.search(_visible(rest)):
            line = next((i + 1 for i, ln in enumerate(lines)
                         if i not in reported and BETA.search(_visible(ln))), 0)
            out.append(f"{rel}:{line or '?'} says Beta ({'edit it by hand' if hand else fix})")
    return out


def _sync(slug: str, entry: dict, root: Path = ROOT) -> None:
    """Make the registry status and the README / pain-point Status paragraphs
    agree with live_verified. The caller writes the registry; the docs page is
    regenerated by build-catalog.py."""
    if entry.get("markdown_only"):
        return
    verified = _verified(entry)
    entry["status"] = "live-verified" if verified else "beta"
    for p, hand in _pages(slug, entry, root):
        if not hand or not p.exists():
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as e:
            print(f"  could not read {p.relative_to(root)} ({e}); left for a person to fix")
            continue
        lines = text.split("\n")
        changed = False
        for (_, _, a, b) in reversed(_status_sections(lines)):
            if a < b and _says_verified("\n".join(lines[a:b])) != verified:
                lines[a:b] = [_status_para(entry, readme=p.name == "README.md")]
                changed = True
        if changed:
            p.write_text("\n".join(lines), encoding="utf-8")
            print(f"  rewrote {p.relative_to(root)} Status")


def cmd_check() -> int:
    skills = _read_registry().get("skills", {})
    bad = [f"{slug}: {d}" for slug, e in sorted(skills.items()) for d in _drift(slug, e)]
    if bad:
        print("verify_live --check: FAIL - Beta and live-verified are mutually exclusive:")
        for b in bad:
            print(f"  - {b}")
        print("  Fix: python3 tools/maintainer/verify_live.py --sync && "
              "python3 tools/maintainer/build-catalog.py")
        return 1
    n = sum(1 for e in skills.values() if _verified(e))
    print(f"verify_live --check: OK ({len(skills)} skills, {n} live-verified, none says Beta)")
    return 0


def cmd_sync() -> int:
    reg = _read_registry()
    for slug, entry in reg.get("skills", {}).items():
        if _drift(slug, entry):
            print(slug)
            _sync(slug, entry)
    _write_registry(reg)
    return 0


def cmd_status() -> int:
    reg = _read_registry()
    skills = {slug: reg["skills"][slug] for slug in sorted(reg.get("skills", {}))}

    headers = ("slug", "status", "date", "source", "evidence")
    rows = []
    for slug, entry in skills.items():
        # A markdown-only skill (e.g. the concierge) recommends + installs other
        # connectors; it has no tenant of its own and so cannot be live-verified.
        # Show "n/a" rather than "awaiting" so it never reads as a pending badge.
        if entry.get("markdown_only"):
            rows.append((slug, "n/a", "-", "-", "markdown-only (no tenant to verify)"))
            continue
        lv = _entry_state(entry)
        rows.append((
            slug,
            lv.get("status") or "awaiting",
            lv.get("date") or "-",
            lv.get("source") or "-",
            lv.get("evidence") or "-",
        ))

    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(str(cell)))

    def fmt(cells: tuple[str, ...]) -> str:
        return "  ".join(str(c).ljust(widths[i]) for i, c in enumerate(cells))

    print(fmt(headers))
    print(fmt(tuple("-" * w for w in widths)))
    for row in rows:
        print(fmt(row))
    return 0


def _print_followup(slug: str, source: str) -> None:
    print()
    print("Next (this command did NOT run these - it is docs-only, no release fires):")
    print("  python3 tools/maintainer/build-catalog.py")
    print(f'  git commit -am "badge: {slug} live-verified ({source})"')


def cmd_verify(
    slug: str,
    source: str,
    evidence: str,
    date: str | None,
    force: bool,
    verified_by: str | None = None,
    issue_url: str | None = None,
    verified_version: str | None = None,
    reported_at: str | None = None,
) -> int:
    reg = _read_registry()
    skills = reg.get("skills", {})
    if slug not in skills:
        print(f"verify_live: unknown slug '{slug}'", file=sys.stderr)
        return 1
    if skills[slug].get("markdown_only"):
        print(
            f"verify_live: refusing '{slug}' - it is markdown-only (no tenant to "
            "verify against). markdown-only skills are not live-verifiable.",
            file=sys.stderr,
        )
        return 1
    if source not in VALID_SOURCES:
        print(
            f"verify_live: --source must be one of {', '.join(VALID_SOURCES)}, "
            f"got '{source}'",
            file=sys.stderr,
        )
        return 1
    if not evidence:
        print("verify_live: --evidence is required (a URL or short note)", file=sys.stderr)
        return 1

    entry = skills[slug]
    current = _entry_state(entry)
    if current.get("status") == "live-verified" and not force:
        print(f"verify_live: '{slug}' is already live-verified.", file=sys.stderr)
        print(f"  date:     {current.get('date') or '-'}", file=sys.stderr)
        print(f"  source:   {current.get('source') or '-'}", file=sys.stderr)
        print(f"  evidence: {current.get('evidence') or '-'}", file=sys.stderr)
        print(
            "  Run with --revoke first, or pass --force to overwrite.",
            file=sys.stderr,
        )
        return 1

    use_date = date or dt.date.today().isoformat()
    # The catalog + per-skill page render `verified_by` (who confirmed it) and
    # `issue_url` (the clickable receipt). A GitHub "it works" report IS its own
    # receipt, so default issue_url to the evidence URL when it points at a
    # github.com issue/PR and the caller did not pass one explicitly.
    use_issue_url = issue_url
    if use_issue_url is None and source == "github" and evidence.startswith(
        "https://github.com/"
    ):
        use_issue_url = evidence
    bound = binding(slug, verified_version, reported_at)
    entry["live_verified"] = {
        "status": "live-verified",
        "date": use_date,
        "source": source,
        "evidence": evidence,
        "verified_by": verified_by,
        "issue_url": use_issue_url,
        **bound,
    }
    _sync(slug, entry)
    _write_registry(reg)

    print(f"{slug}: live-verified ({source}, {use_date})")
    print(f"  evidence:    {evidence}")
    print(f"  verified_by: {verified_by or '(default: Servosity (maintainer))'}")
    print(f"  issue_url:   {use_issue_url or '(none)'}")
    print(f"  verified:    {bound['verified_version'] or 'unknown version'} ({bound['verified_basis']})")
    _print_followup(slug, source)
    return 0


def cmd_bind(slug: str, version: str | None, unknown: bool) -> int:
    """Bind an EXISTING badge to the version it verified (or record that it is
    unknown), leaving its date, source and evidence untouched."""
    if (version is None) == (not unknown):
        raise SystemExit("verify_live: --bind needs exactly one of --verified-version or --unknown")
    reg = _read_registry()
    entry = reg.get("skills", {}).get(slug)
    if entry is None:
        print(f"verify_live: unknown slug '{slug}'", file=sys.stderr)
        return 1
    lv = _entry_state(entry)
    if lv.get("status") != "live-verified":
        print(f"verify_live: '{slug}' is not live-verified; nothing to bind", file=sys.stderr)
        return 1
    lv.update(dict(UNKNOWN_BINDING) if unknown else binding(slug, version))
    entry["live_verified"] = lv
    _write_registry(reg)
    print(f"{slug}: badge bound to {lv['verified_version'] or 'an unknown version'} "
          f"({lv['verified_basis']}{', ' + lv['verified_cli_hash'][:19] + '...' if lv['verified_cli_hash'] else ''})")
    _print_followup(slug, "bind")
    return 0


def cmd_revoke(slug: str) -> int:
    reg = _read_registry()
    skills = reg.get("skills", {})
    if slug not in skills:
        print(f"verify_live: unknown slug '{slug}'", file=sys.stderr)
        return 1
    # Absence of the key IS "awaiting" (tools tolerate it), so revoke removes the
    # key entirely rather than writing an explicit nulled block. This makes a
    # flip -> revoke round-trip a true no-op on skills.json for a skill that had
    # never been verified, leaving the registry byte-for-byte as it started.
    skills[slug].pop("live_verified", None)
    _sync(slug, skills[slug])
    _write_registry(reg)
    print(f"{slug}: reverted to awaiting")
    print()
    print("Next (docs-only, no release fires):")
    print("  python3 tools/maintainer/build-catalog.py")
    print(f'  git commit -am "badge: {slug} reverted to awaiting"')
    return 0


def parse_args(argv: list[str]) -> dict:
    opts: dict = {
        "slug": None,
        "source": None,
        "evidence": None,
        "date": None,
        "verified_by": None,
        "issue_url": None,
        "revoke": False,
        "status": False,
        "check": False,
        "sync": False,
        "self_test": False,
        "force": False,
        "bind": False,
        "unknown": False,
        "verified_version": None,
        "reported_at": None,
    }
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--slug":
            i += 1
            opts["slug"] = argv[i]
        elif a == "--source":
            i += 1
            opts["source"] = argv[i]
        elif a == "--evidence":
            i += 1
            opts["evidence"] = argv[i]
        elif a == "--date":
            i += 1
            opts["date"] = argv[i]
        elif a == "--verified-by":
            i += 1
            opts["verified_by"] = argv[i]
        elif a == "--issue-url":
            i += 1
            opts["issue_url"] = argv[i]
        elif a == "--verified-version":
            i += 1
            opts["verified_version"] = argv[i]
        elif a == "--reported-at":
            i += 1
            opts["reported_at"] = argv[i]
        elif a == "--bind":
            opts["bind"] = True
        elif a == "--unknown":
            opts["unknown"] = True
        elif a == "--revoke":
            opts["revoke"] = True
        elif a == "--status":
            opts["status"] = True
        elif a in ("--check", "--sync"):
            opts[a[2:]] = True
        elif a == "--self-test":
            opts["self_test"] = True
        elif a == "--force":
            opts["force"] = True
        else:
            raise SystemExit(f"verify_live: unknown argument '{a}'")
        i += 1
    return opts


def main(argv: list[str]) -> int:
    opts = parse_args(argv)

    if opts["status"]:
        return cmd_status()
    if opts["self_test"]:
        return _self_test()
    if opts["check"]:
        return cmd_check()
    if opts["sync"]:
        return cmd_sync()

    if opts["revoke"]:
        if not opts["slug"]:
            raise SystemExit("verify_live: --revoke requires --slug")
        return cmd_revoke(opts["slug"])

    if opts["bind"]:
        if not opts["slug"]:
            raise SystemExit("verify_live: --bind requires --slug")
        return cmd_bind(opts["slug"], opts["verified_version"], opts["unknown"])

    if opts["slug"]:
        if not opts["source"]:
            raise SystemExit("verify_live: a flip requires --source")
        return cmd_verify(
            opts["slug"], opts["source"], opts["evidence"], opts["date"], opts["force"],
            verified_by=opts["verified_by"], issue_url=opts["issue_url"],
            verified_version=opts["verified_version"], reported_at=opts["reported_at"],
        )

    raise SystemExit(
        "verify_live: nothing to do. Use --status, --slug ... --source ... "
        "--evidence ..., or --revoke --slug ..."
    )


def _self_test() -> int:
    """Both directions, offline, on a throwaway skills tree: a verified skill
    that still says Beta (registry, Status paragraph, or a stray line) fails;
    an unverified one claiming Live-verified fails; --sync repairs what it can
    and a flip -> revoke round trip of the Status paragraphs is byte-identical."""
    import tempfile

    failures: list[str] = []

    def expect(cond: bool, label: str) -> None:
        print(("  ok   " if cond else "  FAIL ") + label)
        if not cond:
            failures.append(label)

    readme_beta = ("# Acme\n\n> banner\n\n## Status\n\n" + _status_para({"vendor": "Acme"}, True)
                   + "\n\n---\n\nFooter.\n")
    pain_beta = ("# Pain\n\n## Status\n\nBeta. Validated against the Acme API surface; wrapped\n"
                 "over two lines.\n")
    lv = {"status": "live-verified", "source": "github", "verified_by": "@someone (MSP)",
          "issue_url": "https://github.com/Servosity/msp-skills/issues/1"}
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        d = root / "skills" / "acme"
        d.mkdir(parents=True)

        def reset() -> None:
            (d / "README.md").write_text(readme_beta, encoding="utf-8")
            (d / "pain-point.md").write_text(pain_beta, encoding="utf-8")

        reset()
        beta = {"vendor": "Acme", "status": "beta"}
        expect(not _drift("acme", beta, root), "an unverified Beta skill is consistent")
        verified = {"vendor": "Acme", "status": "beta", "live_verified": dict(lv)}
        got = _drift("acme", verified, root)
        expect(len(got) == 3, f"a verified skill saying Beta in registry, README and pain-point -> 3 findings (got {got})")
        _sync("acme", verified, root)
        expect(verified["status"] == "live-verified" and not _drift("acme", verified, root),
               "--sync makes a verified skill consistent")
        readme = (d / "README.md").read_text(encoding="utf-8")
        expect(readme.startswith("# Acme") and "@someone (MSP)" in readme and readme.endswith("---\n\nFooter.\n"),
               "--sync rewrites only the Status paragraph, with the attribution and receipt")
        (d / "README.md").write_text(readme + "\nStill Beta somewhere.\n", encoding="utf-8")
        got = _drift("acme", verified, root)
        expect(len(got) == 1 and "edit it by hand" in got[0], "a stray Beta in a verified README fails, by hand")
        reset()
        _sync("acme", verified, root)
        revoked = {"vendor": "Acme", "status": "live-verified"}
        expect(len(_drift("acme", revoked, root)) == 3, "an unverified skill claiming Live-verified fails")
        _sync("acme", revoked, root)
        expect(revoked["status"] == "beta" and (d / "README.md").read_text(encoding="utf-8") == readme_beta,
               "flip then revoke restores the README Status paragraph byte for byte")
        no_name = {"vendor": "Acme", "status": "live-verified",
                   "live_verified": {"status": "live-verified", "source": "self"}}
        expect(_status_para(no_name, False).startswith("Live-verified. Confirmed by Servosity (maintainer)"),
               "a self receipt with no name credits the maintainer, by source")
        no_name["live_verified"]["source"] = "github"
        expect("Servosity" not in _status_para(no_name, False),
               "a GitHub receipt with no name is never credited to the maintainer")
        expect(not _drift("concierge", {"markdown_only": True, "status": "beta"}, root),
               "a markdown-only skill is out of scope")
        (d / "pain-point.md").write_bytes(b"## Status\n\n\xff\n")
        got = _drift("acme", verified, root)
        expect(any("could not be read" in g for g in got), "an unreadable Status file is a finding, not a pass")
        (d / "pain-point.md").unlink()
        # Codex round 1: valid Markdown must not hide a claim or a Beta.
        unverified = {"vendor": "Acme", "status": "beta"}
        for label, page in [
            ("a Status heading with no blank line after it", "# A\n\n## Status\nLive-verified. Confirmed.\n"),
            ("a bold claim", "# A\n\n## Status\n\n**Live-verified.** Confirmed.\n"),
            ("a Setext Status heading", "A\n=\n\nStatus\n------\n\nLive-verified. Confirmed.\n"),
            ("an indented ATX heading with closing hashes", "# A\n\n   ### Status ###\n\nLive verified, by us.\n"),
            ("a claim in a later Status paragraph", "# A\n\n## Status\n\nBeta.\n\nLive-verified by X.\n"),
        ]:
            (d / "README.md").write_text(page, encoding="utf-8")
            expect(any("claims Live-verified" in g for g in _drift("acme", unverified, root)),
                   f"unverified: {label} is a finding")
        (d / "README.md").write_text("# A\n\n```md\n## Status\n\nLive-verified.\n```\n\n## FAQ\n\n"
                                     "A real MSP run is what earns the live-verified badge.\n\n## Status\n\nBeta.\n",
                                     encoding="utf-8")
        expect(not _drift("acme", unverified, root),
               "unverified: a fenced example and a sentence about the badge outside Status are not claims")
        good = "# A\n\n## Status\n\nLive-verified. Confirmed by X.\n"
        for label, page in [("bold", good + "\n**Beta**\n"), ("an entity", good + "\nBe&#116;a build\n"),
                            ("lower case", good + "\nstill in beta\n")]:
            (d / "README.md").write_text(page, encoding="utf-8")
            expect(any("says Beta" in g for g in _drift("acme", verified, root)),
                   f"verified: Beta as {label} is a finding")
        (d / "README.md").write_text(good, encoding="utf-8")
        docs = root / "docs" / "skills"
        docs.mkdir(parents=True)
        (docs / "acme.md").write_text("# Acme\n\n## Status\n\nBeta. Validated.\n", encoding="utf-8")
        got = _drift("acme", verified, root)
        expect(len(got) == 1 and "docs/skills/acme.md" in got[0] and "build-catalog" in got[0],
               f"verified: a docs page still saying Beta is one finding (got {got})")
        (docs / "acme.md").write_text("# Acme\n\n## Status\n\nLive-verified. Confirmed.\n", encoding="utf-8")
        expect(not _drift("acme", verified, root), "verified: a consistent README and docs page pass")
        expect(any("docs/skills/acme.md" in g for g in _drift("acme", unverified, root)),
               "unverified: a docs page claiming Live-verified is a finding")
    if failures:
        print(f"\nFAIL: verify_live self-test - {len(failures)} case(s)")
        return 1
    print("\nPASS: verify_live - Beta and live-verified exclusivity fires on drift, silent when consistent")
    return 0


